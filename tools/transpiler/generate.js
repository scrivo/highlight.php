'use strict';

/**
 * Generates the PHP language classes from a highlight.js checkout.
 *
 * usage: node generate.js <highlight.js dir> [language...]
 */

const fs = require('fs');
const path = require('path');
const { transpile, className } = require('./transpile');
const { createHljs } = require('./hljs-env');

const hljsDir = process.argv[2];
if (!hljsDir) {
    console.error('usage: node generate.js <highlight.js dir> [language...]');
    process.exit(1);
}

const langDir = path.join(hljsDir, 'src', 'languages');
const outDir = path.join(__dirname, '..', '..', 'src', 'Highlight', 'Languages');
const hljsVersion = JSON.parse(fs.readFileSync(path.join(hljsDir, 'package.json'), 'utf8')).version;

const all = fs.readdirSync(langDir).filter(function (f) { return f.endsWith('.js'); })
    .map(function (f) { return f.slice(0, -3); }).sort();
const selected = process.argv.length > 3 ? process.argv.slice(3) : all;

const env = createHljs(hljsDir);

fs.mkdirSync(outDir, { recursive: true });

let failures = 0;
selected.forEach(function (id) {
    const source = fs.readFileSync(path.join(langDir, id + '.js'), 'utf8');
    try {
        const php = transpile(source, id, { hljsVersion: hljsVersion });
        fs.writeFileSync(path.join(outDir, className(id) + '.php'), php);
    } catch (e) {
        failures++;
        console.error(id + ': ' + e.message);
    }
});

// The registry maps language ids to classes, so languages can be listed and
// loaded without scanning the file system.
const registry = [
    '<?php',
    '',
    '/* This file is generated by tools/transpiler from highlight.js ' + hljsVersion + '. */',
    '',
    'namespace Highlight\\Languages;',
    '',
    '/**',
    ' * @internal',
    ' */',
    'final class Registry',
    '{',
    '    public const HIGHLIGHT_JS_VERSION = \'' + hljsVersion + '\';',
    '',
    '    /** @var array<string, class-string<\\Highlight\\LanguageDefinition>> */',
    '    public const LANGUAGES = [',
].concat(all.map(function (id) {
    return '        \'' + id + '\' => ' + className(id) + '::class,';
})).concat([
    '    ];',
    '',
    '    /**',
    '     * The aliases of each language, so languages can be registered without',
    '     * evaluating their definitions.',
    '     *',
    '     * @var array<string, string[]>',
    '     */',
    '    public const ALIASES = [',
]).concat(all.map(function (id) {
    const aliases = env.define(id).aliases || [];

    return '        \'' + id + '\' => [' + aliases.map(function (a) { return "'" + a.replace(/[\\']/g, '\\$&') + "'"; }).join(', ') + '],';
})).concat([
    '    ];',
    '}',
    '',
]).join('\n');
fs.writeFileSync(path.join(outDir, 'Registry.php'), registry);

console.log('Generated ' + (selected.length - failures) + ' of ' + selected.length + ' languages for highlight.js ' + hljsVersion);
process.exit(failures ? 1 : 0);
